#Take a 3 input from the user
# perform the sub, sub, mul and div
n1=int(input("Enter first number: "))
n2=int(input("Enter second number: "))
n3=int(input("Enter third number: "))

addition = n1 + n2 + n3
print("Addition of three numbers is: ", addition)
subtraction = n1 - n2 - n3
print("Subtraction of three numbers is: ", subtraction)
multiplication = n1 * n2 * n3
print("Multiplication of three numbers is: ", multiplication)
division = n1 / n2 / n3
print("Division of three numbers is: ", division)